// Generates js/core/detect/yamnet-centre.js: the "average sound" that learned
// sounds are compared against (see js/core/detect/learned.js).
//
// YAMNet's embeddings are never negative, so any two sounds already point
// roughly the same way. Subtracting an average sound before comparing removes
// that shared part. The centre is the mean embedding of the sound in a set of
// varied recordings: every 0.975 s window, 0.25 s apart, that is above the
// classifier's −70 dBFS silence gate and within 15 dB of its recording's
// loudest window — the same windows a learned sound is taught from.
//
// A centre made from synthetic noise, tones and chirps was tried and rejected:
// it told sounds apart about as well, but pushed every score up, so at the
// default threshold far more unrelated sounds crossed it.
//
// Usage (from the repository root, Node 20+):
//   node tools/yamnet-centre.mjs recording.wav […]    16-bit PCM WAV, any rate

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { basename, dirname, join } from 'node:path';

globalThis.require = createRequire(import.meta.url); // the flat TF.js build looks for it in Node
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const tf = await import(join(ROOT, 'js/vendor/tf.fesm.min.js'));
const { Resampler } = await import(join(ROOT, 'js/core/resample.js'));
await tf.setBackend('cpu');

const RATE = 16000;
const WINDOW = 15600;
const HOP = 4000;
const GATE_DB = -70;
const SPREAD_DB = 15;

const files = process.argv.slice(2);
if (!files.length) {
  console.error('usage: node tools/yamnet-centre.mjs recording.wav […]');
  process.exit(1);
}

// The model, loaded from the vendored files without a server.
const M = join(ROOT, 'models/yamnet');
const manifest = JSON.parse(readFileSync(join(M, 'model.json'), 'utf8'));
const weights = Buffer.concat(manifest.weightsManifest[0].paths.map((p) => readFileSync(join(M, p))));
const model = await tf.loadGraphModel({
  load: async () => ({
    modelTopology: manifest.modelTopology,
    weightSpecs: manifest.weightsManifest.flatMap((g) => g.weights),
    weightData: weights.buffer.slice(weights.byteOffset, weights.byteOffset + weights.byteLength),
    format: manifest.format,
  }),
});

/** First channel of a 16-bit PCM WAV, and its rate. */
function readWav(path) {
  const b = readFileSync(path);
  let off = 12, rate = 0, channels = 1, bits = 0;
  while (off + 8 <= b.length && b.toString('ascii', off, off + 4) !== 'data') {
    if (b.toString('ascii', off, off + 4) === 'fmt ') {
      channels = b.readUInt16LE(off + 10);
      rate = b.readUInt32LE(off + 12);
      bits = b.readUInt16LE(off + 22);
    }
    off += 8 + b.readUInt32LE(off + 4);
  }
  if (bits !== 16 || !rate) throw new Error(`${path}: not a 16-bit PCM WAV`);
  const n = Math.floor(b.readUInt32LE(off + 4) / 2 / channels);
  const x = new Float32Array(n);
  for (let i = 0; i < n; i++) x[i] = b.readInt16LE(off + 8 + i * 2 * channels) / 32768;
  return { x, rate };
}

const sum = new Float64Array(1024);
let count = 0;
for (const path of files) {
  const { x, rate } = readWav(path);
  const y = new Resampler(rate, RATE).process(x);
  const wins = [];
  for (let s = 0; s + WINDOW <= y.length; s += HOP) {
    const w = y.subarray(s, s + WINDOW);
    let e = 0;
    for (const v of w) e += v * v;
    const db = 10 * Math.log10(e / WINDOW + 1e-20);
    if (db < GATE_DB) continue;
    const emb = tf.tidy(() => {
      const out = model.execute(tf.tensor1d(w.slice()));
      return (Array.isArray(out) ? out : [out]).find((t) => t.shape[t.shape.length - 1] === 1024).mean(0);
    });
    wins.push({ db, v: await emb.data() });
    emb.dispose();
  }
  const top = Math.max(...wins.map((w) => w.db));
  const kept = wins.filter((w) => w.db > top - SPREAD_DB);
  for (const w of kept) for (let i = 0; i < 1024; i++) sum[i] += w.v[i];
  count += kept.length;
  console.error(`${basename(path)}: ${kept.length} windows`);
}

const centre = Array.from(sum, (v) => Number((v / count).toPrecision(4)));
const lines = [];
for (let i = 0; i < 1024; i += 8) lines.push('  ' + centre.slice(i, i + 8).join(', ') + ',');
writeFileSync(join(ROOT, 'js/core/detect/yamnet-centre.js'), `// The "average sound" learned sounds are centred on: the mean YAMNet embedding
// of ${count} windows of sound from ${files.length} recordings — the calibration set
// (animals, voices, crying, laughter, doors, locks, glass,
// sirens, traffic, plus two synthetic tones).
// Generated by tools/yamnet-centre.mjs — regenerate rather than edit by hand.

export const YAMNET_CENTRE = Float32Array.from([
${lines.join('\n')}
]);
`);
console.error(`centre of ${count} windows from ${files.length} recordings written`);
